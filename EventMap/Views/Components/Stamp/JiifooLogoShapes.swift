// 「M x y L x y ... Z」の形の文字列から Path を作り、縦横比を保って rect に収める
enum TracedPath {
    static func fitted(_ data: String, in rect: CGRect) -> Path {
        let path = parse(data)
        let box = path.boundingRect
        guard box.width > 0, box.height > 0 else { return path }
        let scale = min(rect.width / box.width, rect.height / box.height)
        let dx = rect.minX + (rect.width - box.width * scale) / 2 - box.minX * scale
        let dy = rect.minY + (rect.height - box.height * scale) / 2 - box.minY * scale
        return path.applying(CGAffineTransform(a: scale, b: 0, c: 0, d: scale, tx: dx, ty: dy))
    }

    static func parse(_ data: String) -> Path {
        var path = Path()
        let tokens = data
            .replacingOccurrences(of: "M", with: " M ")
            .replacingOccurrences(of: "L", with: " L ")
            .replacingOccurrences(of: "Z", with: " Z ")
            .split(whereSeparator: { $0 == " " || $0 == "\n" })
        var command: Character = "M"
        var numbers: [CGFloat] = []
        for token in tokens {
            if let c = token.first, token.count == 1, "MLZ".contains(c) {
                if c == "Z" { path.closeSubpath() }
                command = c
                numbers = []
                continue
            }
            guard let value = Double(token) else { continue }
            numbers.append(CGFloat(value))
            if numbers.count == 2 {
                let point = CGPoint(x: numbers[0], y: numbers[1])
                if command == "M" { path.move(to: point); command = "L" } else { path.addLine(to: point) }
                numbers = []
            }
        }
        return path
    }
}
